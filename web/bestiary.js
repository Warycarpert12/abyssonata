// pause(on): ставит/снимает паузу мира и возвращает, стояла ли пауза до этого
export function initBestiary({ pause }) {
  let found; try { found = new Set(JSON.parse(localStorage.getItem(KEY) || '[]').filter(sp => BY[sp])); } catch { found = new Set(); }
  const save = () => { try { localStorage.setItem(KEY, JSON.stringify([...found])); } catch { /* приватное окно */ } };
  const $ = id => document.getElementById(id), root = $('bestiary'), body = $('bst-body'), btn = $('bst-btn');
  let isOpen = false, wasPaused = false;
  const esc = s => s.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]));
  const img = (s, cls = '') => `<img class="${cls}${found.has(s.sp) ? '' : ' dark'}${s.small ? ' small' : ''}" src="bestiary/${s.img}.png" alt="" draggable="false">`;
  const count = () => { $('bst-count').textContent = `найдено ${found.size} из ${SPECIES.length}`; };
  const grid = () => {
    count(); body.scrollTop = 0;
    body.innerHTML = Object.entries(G).map(([g, title]) => `<h4>${title}</h4><div class="bst-grid">` +
      SPECIES.filter(s => s.g === g).map(s => `<button class="bst-card${found.has(s.sp) ? '' : ' off'}" data-sp="${s.sp}">${img(s)}<span>${found.has(s.sp) ? esc(s.name) : '???'}</span></button>`).join('') + '</div>').join('');
  };
  const card = sp => {
    const s = BY[sp], ok = found.has(sp); body.scrollTop = 0;
    body.innerHTML = `<button class="bst-back">← все виды</button><div class="bst-card-full"><div class="bst-pic">${img(s, 'big')}</div><div class="bst-txt">` + (ok
      ? `<h3>${esc(s.name)}</h3><i>${esc(s.latin)}</i><p>${esc(s.about)}</p><h5>Интересно</h5><ul>${s.facts.map(f => `<li>${esc(f)}</li>`).join('')}</ul>` +
        `<h5>Где живёт</h5><p>${esc(s.home)}</p><h5>Что ест</h5><p>${esc(s.food)}</p><h5>В нашем океане</h5><p>${esc(s.here)}</p>`
      : `<h3>???</h3><p>Этот вид ещё не найден. Наведи на зверя, выбери его в «Обитателях» или проследи за ним — и карточка откроется.</p>`) + '</div></div>';
  };
  body.addEventListener('click', e => {
    const c = e.target.closest('.bst-card'); if (c) return card(c.dataset.sp);
    if (e.target.closest('.bst-back')) grid();
  });
  const open = () => { if (isOpen) return; isOpen = true; wasPaused = pause(true); root.hidden = false; btn.classList.remove('new'); grid(); };
  const close = () => { if (!isOpen) return; isOpen = false; root.hidden = true; if (!wasPaused) pause(false); };
  btn.addEventListener('click', () => (isOpen ? close() : open()));
  $('bst-close').addEventListener('click', close);
  root.addEventListener('pointerdown', e => { if (e.target === root) close(); });   // нажатие мимо окна — закрыть
  addEventListener('keydown', e => { if (e.key === 'Escape' && isOpen) close(); });
  return {
    get open() { return isOpen; },
    discover(sp) {   // новый вид — подсветить кнопку (пока бестиарий закрыт)
      if (!BY[sp] || found.has(sp)) return;
      found.add(sp); save();
      if (isOpen) count(); else btn.classList.add('new');
    },
  };
}
